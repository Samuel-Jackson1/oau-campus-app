// build-icons.mjs - packs the category icons into category-icons.js for the app.
//
// The SVG files in icons/categories/ are the originals (designed by Timi, Front End;
// redrawn as single-colour line icons). Edit an SVG there, then run:
//
//   npm run icons
//
// and raise the version in sw.js so phones fetch the new icons.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Category name (exactly as in places.json) -> SVG file in icons/categories/. "_" is the default pin.
const FILES = {
  'Lecture Theatres': 'lecture-theatres.svg',
  'Faculties': 'faculties.svg',
  'Hostels': 'hostels.svg',
  'Libraries': 'libraries.svg',
  'Administration': 'administration.svg',
  'Essential Services': 'essential-services.svg',
  'Gates': 'gates.svg',
  'Food & Shops': 'food-and-shops.svg',
  'Sports': 'sports.svg',
  '_': 'default-pin.svg'
};

const icons = {};
for (const [category, file] of Object.entries(FILES)) {
  icons[category] = (await readFile(path.join(ROOT, 'icons', 'categories', file), 'utf8')).trim();
}

const out = `// category-icons.js - GENERATED by tools/build-icons.mjs from icons/categories/*.svg. Do not edit by hand.
// Replaces the starter's placeholder category icons (vendor/icons.js) with the group's own set.
Object.assign(MAKI, ${JSON.stringify(icons, null, 1)});
`;
await writeFile(path.join(ROOT, 'category-icons.js'), out, 'utf8');
console.log(`Wrote category-icons.js with ${Object.keys(icons).length} icons.`);
